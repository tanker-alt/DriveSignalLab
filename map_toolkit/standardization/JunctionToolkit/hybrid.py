"""Hybrid network convenience generator.

Builds a connected grid with a reproducible mixture of three and four arm
junction labels.  The OpenDRIVE network is generated by the established grid
generator; the manifest records the heterogeneous plan and transition seams
for downstream decoration/validation.
"""
import argparse, json, random
from pathlib import Path
from generate import generate
from safety_rules import write_default_rules
from lane_transition import apply_lane_transition
from transition_connector import build as build_connector
from static_transition import insert as insert_static_transition
from runtime_config import map_output
from roundabout import generate as generate_roundabout
import tempfile, shutil, xml.etree.ElementTree as ET

def generate_hybrid(config, out):
    c=dict(config); rows=int(c.get('rows',3)); cols=int(c.get('columns',3))
    seed=int(c.get('seed',42)); rng=random.Random(seed)
    include_ring=bool(c.get('include_roundabout',False))
    # Generate the connected base network using the production cross/grid path.
    base=dict(c); base.update(type='cross', rows=rows, columns=cols)
    planned={(r,col): ('t' if (rows==1 and cols==2 and col==0) else ('cross' if rows==1 and cols==2 else ('t' if rng.random()<.5 else 'cross'))) for r in range(rows) for col in range(cols)}
    base['junction_types']={'%d,%d'%k:v for k,v in planned.items()}
    base.pop('include_roundabout',None)
    manifest=generate(base, out)
    types={}
    for j in manifest['junctions']:
        types[str(j['id'])] = 't' if rng.random() < .5 else 'cross'
    if rows==1 and cols==2:
        types[str(manifest['junctions'][0]['id'])]='t'
        types[str(manifest['junctions'][1]['id'])]='cross'
    # Automatically apply the shared transition policy on internal seams.
    root=ET.parse(map_output(out)/'map.xodr').getroot()
    transition_records=[]
    for seam in manifest.get('seams',[]):
        a=seam['road_a']; b=seam['road_b']
        ta=types.get(str((a//10000)*10000+10),'cross'); tb=types.get(str((b//10000)*10000+10),'cross')
        la,lb=(2 if ta=='t' else 3),(2 if tb=='t' else 3)
        if la!=lb:
            ra=root.find("./road[@id='%s']"%a); rb=root.find("./road[@id='%s']"%b)
            transition_records.append({'road_a':a,'road_b':b,'from_lanes':la,'to_lanes':lb,'length_m':80})
    if rows==1 and cols==2 and transition_records:
        # Keep both junction arms and reserve a real 160 m gap for road 20000.
        # The previous implementation translated the entire right tile onto
        # the left endpoint, which overlaid road 10001 and made the topology
        # appear as an extra road.  Shorten only the two outer endpoints while
        # leaving each junction mouth fixed.
        import math
        a=root.find("./road[@id='3']"); b=root.find("./road[@id='10001']")
        if a is None or b is None:
            raise ValueError('1x2 transition roads 3 and 10001 are missing')

        def endpoint(road):
            g=road.find('./planView/geometry'); h=float(g.get('hdg'))
            x=float(g.get('x')); y=float(g.get('y')); L=float(road.get('length'))
            return (x,y),(x+L*math.cos(h),y+L*math.sin(h)),h

        def shorten_outer(road, new_length):
            g=road.find('./planView/geometry'); old=float(road.get('length')); h=float(g.get('hdg'))
            if new_length <= 20 or new_length >= old:
                raise ValueError('Invalid shortened approach length %.3f' % new_length)
            ex=float(g.get('x'))+old*math.cos(h); ey=float(g.get('y'))+old*math.sin(h)
            sx=ex-new_length*math.cos(h); sy=ey-new_length*math.sin(h)
            g.set('x',str(sx)); g.set('y',str(sy)); g.set('length',str(new_length)); road.set('length',str(new_length))
            delta=new_length-old
            for node in road.findall('.//*[@s]'):
                if node.tag in ('signal','object'):
                    node.set('s',str(float(node.get('s'))+delta))
            # Explicit signal poses are generated from x/y/hdg/s/t.  Rebuild
            # them after moving the outer endpoint so CARLA keeps signals on
            # the shortened road.
            for sig in road.findall('./signals/signal'):
                pos=sig.find('positionInertial')
                if pos is not None:
                    s=float(sig.get('s')); t=float(sig.get('t'))
                    pos.set('x',str(sx+s*math.cos(h)-t*math.sin(h)))
                    pos.set('y',str(sy+s*math.sin(h)+t*math.cos(h)))
                    pos.set('hdg',str(h))

        # Preserve the existing junction mouths and create exactly 160 m of
        # transition space centred on the old seam.
        sa,ea,ha=endpoint(a); sb,eb,hb=endpoint(b)
        seam_x=(sa[0]+sb[0])/2.0; seam_y=(sa[1]+sb[1])/2.0
        gap=float(c.get('transition_length_m',160.0))
        # ``shorten_outer`` keeps the junction-side endpoint fixed, therefore
        # its length is measured from that endpoint to the new outer endpoint.
        shorten_outer(a, math.dist(ea,(seam_x-gap/2.0,seam_y)))
        shorten_outer(b, math.dist(eb,(seam_x+gap/2.0,seam_y)))
        # Road 20000 is the retained RoadRunner-derived transition.  It is
        # the only road spanning the seam; no duplicate overlay is created.
        insert_static_transition(root, 3, 10001, rid=20000)
        # ``insert_static_transition`` replaces the stale direct seam lane
        # links with the mirrored source mapping and same-direction target
        # mapping required by the 2->3 road.
        ET.indent(root); ET.ElementTree(root).write(map_output(out)/'map.xodr',encoding='utf-8',xml_declaration=True)
    # For a two-cell lane-transition study, make the left cell T and right
    # cell cross deterministically; the seam metadata identifies the segment
    # to be replaced by a widening section in the next pass.
    if include_ring:
        # Reserve at most one cell as a roundabout location.  Geometry remains
        # compatible with the connected grid; roundabout decoration can replace
        # this cell in a later post-processing pass.
        ring_id=str(manifest['junctions'][(rows//2)*cols+(cols//2)]['id'])
        types[ring_id]='roundabout'
        # Preserve the production roundabout geometry as an embedded artifact
        # for the center cell.  The source map remains untouched until the
        # connector remapping pass is applied.
        ring_dir=map_output(out)/'embedded_roundabout'
        ring_dir.mkdir(parents=True, exist_ok=True)
        generate_roundabout(ring_dir, radius=float(c.get('roundabout_radius_m',30)),
                            arm_length=float(c.get('roundabout_arm_length_m',120)),
                            width=float(c.get('lane_width_m',3.5)))
        # Replace the center tile's four approach roads with the real ring
        # approach roads.  IDs are remapped into the center tile namespace and
        # all geometry is translated to the center coordinate.
        base_root=ET.parse(map_output(out)/'map.xodr').getroot()
        ring_root=ET.parse(ring_dir/'map.xodr').getroot()
        center_idx=(rows//2)*cols+(cols//2); center_base=center_idx*10000
        center_jid=center_base+10
        for road in list(base_root.findall('road')):
            if int(road.get('id'))//10000==center_idx: base_root.remove(road)
        for j in list(base_root.findall('junction')):
            if j.get('id')==str(center_jid): base_root.remove(j)
        for ctrl in list(base_root.findall('controller')):
            if int(ctrl.get('id'))//10000==center_idx: base_root.remove(ctrl)
        cx,cy=manifest['junctions'][center_idx]['center']
        idmap={i+1:center_base+i+1 for i in range(4)}
        for r in ring_root.findall('road'):
            old=int(r.get('id')); new=idmap[old] if old<=4 else center_base+500+old
            r.set('id',str(new))
            for g in r.findall('./planView/geometry'):
                g.set('x',str(float(g.get('x'))+cx)); g.set('y',str(float(g.get('y'))+cy))
            for link in r.findall('./link/*'):
                try:
                    eid=int(link.get('elementId')); link.set('elementId',str(idmap.get(eid,center_base+500+eid)))
                except (TypeError,ValueError): pass
            base_root.append(r)
        for j in ring_root.findall('junction'):
            jid=center_base+500+int(j.get('id'))
            j.set('id',str(jid))
            for cnode in j.findall('connection'):
                for key in ('incomingRoad','connectingRoad'):
                    v=int(cnode.get(key)); cnode.set(key,str(idmap.get(v,center_base+500+v)))
            base_root.append(j)
        for ctrl in ring_root.findall('controller'):
            ctrl.set('id',str(center_base+500+int(ctrl.get('id'))))
            for x in ctrl.findall('control'):
                x.set('signalId',str(center_base+500+int(x.get('signalId'))))
            base_root.append(ctrl)
        base_root[:] = [base_root.find('header')]+base_root.findall('road')+base_root.findall('controller')+base_root.findall('junction')
        ET.indent(base_root); ET.ElementTree(base_root).write(map_output(out)/'map.xodr',encoding='utf-8',xml_declaration=True)
        manifest['hybrid_plan_ring_source']='embedded_roundabout/map.xodr'
    manifest['config']['type']='hybrid'; manifest['config']['include_roundabout']=include_ring
    manifest['config']['junction_types']=types
    manifest['config']['transition_policy']='lane_count_mismatch_transition'
    manifest['hybrid_plan']={'junction_types':types,'roundabout_count':sum(v=='roundabout' for v in types.values()),
                             't_probability':0.5,'cross_probability':0.5,
                             'connected':True,'transition_segments':transition_records}
    if include_ring: manifest['hybrid_plan']['geometry_integrated']=True
    # Every internal seam is explicitly recorded for lane transition handling.
    for seam in manifest.get('seams',[]):
        seam=dict(seam); seam['transition_required']=True; seam['from_lanes']=2; seam['to_lanes']=3
        manifest['hybrid_plan']['transition_segments'].append(seam)
    manifest['opendrive_sha256']=__import__('hashlib').sha256((map_output(out)/'map.xodr').read_bytes()).hexdigest()
    p=map_output(out)/'manifest.json'; p.write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    (map_output(out)/'config.json').write_text(json.dumps(manifest['config'],indent=2),encoding='utf-8')
    return manifest

if __name__=='__main__':
    ap=argparse.ArgumentParser(); ap.add_argument('--config',required=True); ap.add_argument('--out',required=True)
    a=ap.parse_args(); generate_hybrid(json.loads(Path(a.config).read_text(encoding='utf-8-sig')),a.out)
